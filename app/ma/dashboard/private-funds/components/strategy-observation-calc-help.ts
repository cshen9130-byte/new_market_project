function categorySentence(strategy: string): string {
  if (strategy === "500指增" || strategy === "300指增" || strategy === "A500指增" || strategy === "2000指增") {
    return "匹配方式和 1000指增 相同：二级等于该分类，或三级含该分类，或二级、三级、产品名命中对应指数增强关键词。名称已识别为 A500 的产品不进 500指增。"
  }
  const rule = CATEGORY_RULES.bullets?.find((item) => {
    const head = item.split("：")[0] ?? ""
    return head.split("、").some((name) => name.trim() === strategy)
  })
  if (rule) return rule
  const embedded = CATEGORY_RULES.bullets?.find((item) => item.includes(`${strategy}：`))
  return embedded ?? "归类规则见收益表现表格「分类」旁的问号。"
}

